import time
import pytest
from datetime import date, time as dt_time, timedelta
from app.solver.dtos import (
    SolverInputDTO,
    SolverConfigDTO,
    ShiftInstanceRequirementDTO,
)
from app.solver.services.schedule_solver_service import ScheduleSolverService
from app.rules.dtos import WorkerDTO, ShiftTypeDTO
from app.services.schedule_service import ScheduleService


def test_cp_sat_solver_performance_50_workers():
    """Benchmark CP-SAT solver setup and solve time for a 50-worker schedule over 7 days."""
    solver_service = ScheduleSolverService()

    start_date = date(2026, 8, 1)
    end_date = date(2026, 8, 7)

    # 50 Workers with complete required DTO fields
    workers = {
        f"worker-{i}": WorkerDTO(
            id=f"worker-{i}",
            employee_number=f"EMP-{i:03d}",
            first_name="Worker",
            last_name=f"{i}",
            department_id="dept-1",
            active=True
        )
        for i in range(1, 51)
    }

    # 4 Shift Types with complete required DTO fields
    shift_types = {
        "st-morning": ShiftTypeDTO(
            id="st-morning",
            name="Morning",
            start_time=dt_time(6, 0),
            end_time=dt_time(14, 0),
            duration=8.0,
            is_night_shift=False
        ),
        "st-day": ShiftTypeDTO(
            id="st-day",
            name="Day",
            start_time=dt_time(9, 0),
            end_time=dt_time(17, 0),
            duration=8.0,
            is_night_shift=False
        ),
        "st-evening": ShiftTypeDTO(
            id="st-evening",
            name="Evening",
            start_time=dt_time(14, 0),
            end_time=dt_time(22, 0),
            duration=8.0,
            is_night_shift=False
        ),
        "st-night": ShiftTypeDTO(
            id="st-night",
            name="Night",
            start_time=dt_time(22, 0),
            end_time=dt_time(6, 0),
            duration=8.0,
            is_night_shift=True
        ),
    }

    # Shift Requirements per day (4 shifts/day * 7 days = 28 instances)
    requirements = []
    curr = start_date
    req_id = 1
    while curr <= end_date:
        for st_id in shift_types.keys():
            requirements.append(
                ShiftInstanceRequirementDTO(
                    id=f"req-{req_id}",
                    date=curr,
                    shift_type_id=st_id,
                    required_workers=2
                )
            )
            req_id += 1
        curr += timedelta(days=1)

    input_data = SolverInputDTO(
        start_date=start_date,
        end_date=end_date,
        workers=workers,
        shift_types=shift_types,
        shift_requirements=requirements,
        config=SolverConfigDTO(time_limit_seconds=10, num_search_workers=4)
    )

    t0 = time.time()
    result = solver_service.solve(input_data)
    runtime = time.time() - t0

    assert result.is_solved, "Solver failed to find a valid schedule solution"
    assert runtime < 10.0, f"Solver exceeded benchmark runtime target of 10s: took {runtime:.2f}s"
    assert len(result.assignments) > 0, "No assignments generated by solver"


